// 3 AM Rule helper
export const getAdjustedDateLabel = (date: Date): string => {
  const d = new Date(date);
  if (d.getHours() < 3) {
    d.setDate(d.getDate() - 1);
  }
  return d.toISOString().split('T')[0];
};

